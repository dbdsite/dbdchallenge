(function applyPickRateClassification(){
  const normalize = value => String(value || "")
    .toLowerCase().normalize("NFKD")
    .replace(/\\xa0/g, " ")
    .replace(/[^a-z0-9]+/g, "");
  const stripAssetPrefix = value => normalize(value).replace(/^(t)?icon(s)?perks?/, "");
  const aliases = {
    anursescalling: "a nurses calling", awakenedawarenesss: "awakened awareness",
    bbqandchili: "barbecue & chili", barbecuechilli: "barbecue & chili",
    hexbloodfavour: "hex: blood favor", boondestroyer: "shattered hope",
    cruelconfinement: "cruel limits", darknessrevelated: "darkness revealed",
    deadmanswitch: "dead man’s switch", floodofrage: "scourge hook: floods of rage",
    franklinsloss: "franklin’s demise", friendstilltheend: "friends ’til the end",
    generatorovercharge: "overcharge", hangmanstrick: "scourge hook: hangman’s trick",
    imallears: "i'm all ears", mindbreaker: "fearmonger",
    monstrousshrine: "scourge hook: monstrous shrine", nooneescapesdeath: "hex: no one escapes death",
    painresonance: "scourge hook: pain resonance", ruin: "hex: ruin",
    devourhope: "hex: devour hope", hauntedground: "hex: haunted ground",
    huntresslullaby: "hex: huntress lullaby", thethirdseal: "hex: the third seal",
    thrillofthehunt: "hex: thrill of the hunt", twocanplay: "hex: two can play",
    thatanophobia: "thanatophobia", quickandquiet: "quick & quiet",
    darktheory: "boon: dark theory", illumination: "boon: illumination",
    vittoriosgambit: "quick gambit", wellmakeit: "we'll make it",
    fixated: "self-aware", secondwind: "renewal", bettertogether: "situational awareness",
    babysitter: "guardian", innerstrength: "inner healing", camaraderie: "kinship",
    surge: "jolt", weregonnaliveforever: "we're gonna live forever"
  };
  function classify(role, perks){
    const source = window.PERK_PICK_RATES[role];
    const byName = new Map(Object.entries(source).map(([name, rate]) => [normalize(name), {sourceName:name, rate}]));
    const ranked = [];
    for (const perk of perks) {
      const info = PERK_DETAILS?.[perk.image];
      if (info?.role !== role) continue;
      const rawName = info?.englishName || perk.englishName;
      const key = stripAssetPrefix(rawName);
      const alias = aliases[key];
      const match = byName.get(key) || (alias && byName.get(normalize(alias)));
      if (!match) continue;
      perk.pickRate = match.rate;
      perk.pickRateSourceName = match.sourceName;
      ranked.push(perk);
    }
    const values = ranked.map(perk => perk.pickRate).sort((a,b)=>a-b);
    const median = values[Math.floor(values.length / 2)] ?? 0;
    return {
      good: ranked.filter(perk => perk.pickRate >= median),
      bad: ranked.filter(perk => perk.pickRate < median),
      median, tracked: ranked.length
    };
  }
  const killer = classify("killer", killerPerks);
  const survivor = classify("survivor", survivorPerks);
  PERK_CATEGORIES.killerGood = killer.good;
  PERK_CATEGORIES.killerBad = killer.bad;
  PERK_CATEGORIES.survivorGood = survivor.good;
  PERK_CATEGORIES.survivorBad = survivor.bad;
  window.PERK_PICK_RATE_META = { snapshot: window.PERK_PICK_RATES.snapshot,
    rule: "Хороший — пикрейт не ниже медианы для своей роли; плохой — ниже медианы.",
    killer: {median:killer.median, tracked:killer.tracked}, survivor: {median:survivor.median, tracked:survivor.tracked}
  };
})();
